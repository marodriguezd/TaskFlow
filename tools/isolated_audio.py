#!/usr/bin/env python3
"""Isolated ALSA playback device that records every sample to a private file.

JavaFX decodes WAV through its pure-Java platform, which uses Java Sound and
ALSA on Linux. This module points that path at a per-test ALSA configuration
whose default PCM is the built-in ``file`` plugin backed by the ``null`` PCM:
every sample the application "plays" is written to a file inside the test's
temporary directory instead of a sound card.

Isolation properties:

* the configuration is supplied only through ``ALSA_CONFIG_PATH`` for the test
  process; the host's ``/etc/asound.conf``, default device, mixer state and
  running audio servers are never read or modified;
* there is no hardware device in that configuration, so no sample can reach the
  machine's speakers or headphones;
* ``PULSE_SERVER`` and ``PIPEWIRE_RUNTIME_DIR`` are redirected to non-existent
  private paths so a JavaFX/GStreamer path that prefers PulseAudio or PipeWire
  fails closed instead of connecting to the host's audio server;
* ``assert_isolated()`` re-checks the active configuration before every launch.

Capture files are raw signed 16-bit little-endian PCM, so no WAV header has to
be finalised when playback stops.

Usage is internal to ``tools/acceptance_check.py``::

    audio = IsolatedAudio(root).start()
    capture = audio.begin_capture()      # must precede the app launch
    ...launch the app and trigger a completion...
    assert capture.peak() > 100
"""

from __future__ import annotations

import os
import shutil
from pathlib import Path

SAMPLE_RATE = 44100
CHANNELS = 2
SAMPLE_WIDTH = 2


class AudioIsolationError(RuntimeError):
    """The isolated capture device could not be prepared or is not isolated."""


def pcm_peak(frames: bytes) -> int:
    """Peak absolute signed 16-bit little-endian sample of raw PCM bytes."""
    return max(
        (
            abs(int.from_bytes(frames[index : index + 2], "little", signed=True))
            for index in range(0, len(frames) - 1, 2)
        ),
        default=0,
    )


def wav_peak(path: Path) -> int:
    """Peak absolute 16-bit sample of a PCM WAV file (0 for empty/silence)."""
    import wave

    try:
        with wave.open(str(path)) as audio:
            frames = audio.readframes(audio.getnframes())
    except (wave.Error, OSError):
        return 0
    return pcm_peak(frames)


class Capture:
    """The ALSA file PCM of one application launch."""

    def __init__(self, path: Path, config: Path):
        self.path = path
        self.config = config

    def reset(self) -> "Capture":
        if self.path.exists():
            self.path.unlink()
        return self

    def raw(self) -> bytes:
        try:
            return self.path.read_bytes()
        except OSError:
            return b""

    def frames(self) -> int:
        return len(self.raw()) // (CHANNELS * SAMPLE_WIDTH)

    def peak(self) -> int:
        return pcm_peak(self.raw())

    def is_silent(self) -> bool:
        return self.peak() == 0


class IsolatedAudio:
    """Creates per-launch ALSA file-PCM configurations inside ``root``."""

    def __init__(self, root: Path):
        self.root = Path(root)
        self.config_dir = self.root / "alsa"
        self.capture_dir = self.root / "audio-captures"
        self._capture: Capture | None = None
        self._base_env: dict[str, str] | None = None
        self._index = 0

    # ---------------------------------------------------------------- lifecycle
    def start(self) -> "IsolatedAudio":
        self.config_dir.mkdir(parents=True, exist_ok=True)
        self.capture_dir.mkdir(parents=True, exist_ok=True)
        env = os.environ.copy()
        # Fail closed: never let a PulseAudio/PipeWire client reach the host.
        env["PULSE_SERVER"] = f"unix:{self.root}/no-pulse-server"
        env.pop("PULSE_SINK", None)
        env.pop("PULSE_RUNTIME_PATH", None)
        env["PIPEWIRE_RUNTIME_DIR"] = str(self.root / "no-pipewire")
        env.pop("PIPEWIRE_REMOTE", None)
        self._base_env = env
        self.begin_capture()
        return self

    def close(self) -> None:
        shutil.rmtree(self.config_dir, ignore_errors=True)
        shutil.rmtree(self.capture_dir, ignore_errors=True)
        self._capture = None

    def __enter__(self) -> "IsolatedAudio":
        return self.start()

    def __exit__(self, *exc_info: object) -> None:
        self.close()

    # ------------------------------------------------------------------ capture
    def begin_capture(self) -> Capture:
        """Select a fresh capture file; call before launching the application."""
        self._index += 1
        raw = self.capture_dir / f"playback-{self._index}.raw"
        config = self.config_dir / f"asound-{self._index}.conf"
        config.write_text(
            "# Generated by tools/isolated_audio.py - never installed on the host.\n"
            'pcm.null { type null }\n'
            'pcm.!default {\n'
            '    type file\n'
            '    slave.pcm "null"\n'
            f'    file "{raw}"\n'
            '    format "raw"\n'
            '}\n',
            encoding="utf-8",
        )
        capture = Capture(raw, config).reset()
        self._capture = capture
        self.assert_isolated()
        self._assert_no_host_server_reachable()
        return capture

    @property
    def capture(self) -> Capture:
        if self._capture is None:
            raise AudioIsolationError("begin_capture() has not run")
        return self._capture

    def env(self) -> dict[str, str]:
        if self._base_env is None:
            raise AudioIsolationError("start() has not run")
        env = dict(self._base_env)
        env["ALSA_CONFIG_PATH"] = str(self.capture.config)
        return env

    # ------------------------------------------------------------------- checks
    def assert_isolated(self) -> None:
        """Refuse to continue unless the active configuration writes to our file."""
        if self._capture is None:
            raise AudioIsolationError("no capture has been prepared")
        config = self._capture.config
        text = config.read_text(encoding="utf-8")
        if "type file" not in text or 'slave.pcm "null"' not in text:
            raise AudioIsolationError(f"unexpected ALSA configuration: {config}")
        if str(self._capture.path) not in text:
            raise AudioIsolationError(
                f"the ALSA file PCM does not target the private capture: {config}"
            )
        path = self._capture.path.resolve()
        if self.root.resolve() not in path.parents:
            raise AudioIsolationError(f"capture file escapes the temporary root: {path}")
        env = self.env()
        if env.get("ALSA_CONFIG_PATH") != str(config):
            raise AudioIsolationError("the application would not use the isolated ALSA device")
        for key in ("PULSE_SERVER", "PIPEWIRE_RUNTIME_DIR"):
            if str(self.root) not in env.get(key, ""):
                raise AudioIsolationError(f"{key} is not redirected away from the host")

    def _assert_no_host_server_reachable(self) -> None:
        # A socket path inside our temporary directory cannot be the host server.
        for key in ("PULSE_SERVER", "PIPEWIRE_RUNTIME_DIR"):
            value = self._base_env.get(key, "")
            if str(self.root) not in value:
                raise AudioIsolationError(f"{key} could reach the host audio server: {value}")
